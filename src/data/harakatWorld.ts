/** كلمة مثال داخل درس الحركة */
export interface HarakaExample {
  /** الكلمة كاملة مشكولة */
  word: string
  /** المقطع المستهدف داخل الكلمة — يُلوَّن بلون الحركة */
  highlight: string
  /** إيموجي يمثّل الكلمة (يظهر بدل الصورة إذا لم توجد) */
  emoji: string
  /** اسم ملف الصورة داخل /images/harakat/ — اختياري */
  image?: string
  /** نص كامل يُرسَل للاستوديو — جملة شارحة وليس مجرد مقطع */
  speechText: string
}

/** سؤال تفاعلي داخل الدرس */
export interface HarakaQuestion {
  id: string
  /** نص السؤال المعروض */
  prompt: string
  /** النص المنطوق للسؤال */
  speechText: string
  options: string[]
  answer: string
  /** نوع السؤال لاستخدامه في لعبة متنوعة */
  type: 'identify_haraka' | 'identify_word' | 'identify_syllable' | 'complete_word' | 'sentence_haraka'
}

/** مدخل واحد كامل في عالم الحركات والمقاطع */
export interface HarakaWorldEntry {
  id: HarakaWorldId
  /** اسم الحركة */
  label: string
  /** رمز الحركة للعرض البصري */
  symbol: string
  /** إيموجي يمثّل الحركة */
  emoji: string
  /** وصف مبسّط للطفل */
  description: string
  /** نص النطق للشرح — يُرسَل للاستوديو */
  descriptionSpeech: string
  /** جملة تعريفية مختصرة تُنطق عند فتح البطاقة */
  introSpeech: string
  /** لون البطاقة (hex) */
  color: string
  /** الأمثلة (3–5 كلمات) */
  examples: HarakaExample[]
  /** جملة كاملة تحتوي الحركة */
  sentence: string
  /** نطق الجملة الكاملة */
  sentenceSpeech: string
  /** أسئلة تفاعلية (3–5 أسئلة متنوعة) */
  questions: HarakaQuestion[]
}

